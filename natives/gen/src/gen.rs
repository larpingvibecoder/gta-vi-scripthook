//! Code generation: `natives.h` (C++ namespaces over scripthook.hpp), `natives_c.h` (C, over
//! scripthook.h) and `natives.rs` (Rust modules over scripthook-sdk).

use crate::db::{Args, Db, Native, Ret};
use scripthook_sdk::natives::Type;
use std::collections::{BTreeMap, BTreeSet};

fn ident(s: &str) -> String {
    let mut o: String = s.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    if o.is_empty() || o.chars().next().unwrap().is_ascii_digit() {
        o.insert(0, '_');
    }
    o
}

fn by_namespace(db: &Db) -> BTreeMap<String, Vec<&Native>> {
    let mut m: BTreeMap<String, Vec<&Native>> = BTreeMap::new();
    for n in &db.natives {
        let ns = if n.namespace().is_empty() { "NATIVES".to_string() } else { n.namespace().to_string() };
        m.entry(ns).or_default().push(n);
    }
    for v in m.values_mut() {
        v.sort_by(|a, b| a.short().cmp(b.short()));
    }
    m
}

/// Handle-type spellings used as `int` (Ped, Vehicle, Entity, ...): generated as aliases.
fn aliases(db: &Db) -> BTreeSet<String> {
    let mut s = BTreeSet::new();
    let mut add = |sp: &str, t: Type| {
        let base = sp.trim().trim_end_matches('*').trim();
        if matches!(t, Type::Int | Type::OutInt) && !base.is_empty() && base.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') && !base.chars().next().unwrap().is_ascii_digit() {
            let l = base.to_ascii_lowercase();
            if !["int", "out_int", "int32", "int32_t", "uint", "u32", "hash"].contains(&l.as_str()) {
                s.insert(base.to_string());
            }
        }
    };
    for n in &db.natives {
        if let Args::Types(v) = &n.args {
            for (sp, t) in v {
                add(sp, *t);
            }
        }
        if let Ret::Type(sp, t) = &n.ret {
            add(sp, *t);
        }
    }
    s
}

fn param_names(n: &Native, count: usize) -> Vec<String> {
    (0..count).map(|i| n.params.get(i).map(|p| ident(p)).filter(|p| !p.is_empty() && p != "_").unwrap_or_else(|| format!("p{i}"))).collect()
}

fn id_text(n: &Native) -> String {
    n.id.map(|i| i.text()).unwrap_or_else(|| "unknown".into())
}

fn alias_or<'a>(sp: &'a str, als: &BTreeSet<String>, dflt: &'a str) -> String {
    let base = sp.trim().trim_end_matches('*').trim();
    if als.contains(base) {
        base.to_string()
    } else {
        dflt.to_string()
    }
}

// ---- C++ ------------------------------------------------------------------------------------

fn cpp_arg(sp: &str, t: Type, als: &BTreeSet<String>) -> String {
    match t {
        Type::Int => alias_or(sp, als, "int32_t"),
        Type::Float => "float".into(),
        Type::Bool => "bool".into(),
        Type::Hash => "shk::Hash".into(),
        Type::Str => "const char*".into(),
        Type::Vec3 => "shk::Vec3".into(),
        Type::U64 | Type::Ptr => "uint64_t".into(),
        Type::OutInt => format!("{}*", alias_or(sp, als, "int32_t")),
        Type::OutFloat => "float*".into(),
        Type::OutBool => "shk::OutBool".into(),
        Type::OutVec3 => "shk::Vec3*".into(),
        Type::Void => "void".into(),
    }
}

fn cpp_ret(r: &Ret, als: &BTreeSet<String>) -> String {
    match r {
        Ret::Unknown => "int32_t".into(),
        Ret::Type(_, Type::Void) => "void".into(),
        Ret::Type(sp, Type::Int) => alias_or(sp, als, "int32_t"),
        Ret::Type(_, Type::Float) => "float".into(),
        Ret::Type(_, Type::Bool) => "bool".into(),
        Ret::Type(_, Type::Hash) => "shk::Hash".into(),
        Ret::Type(_, Type::Str) => "std::string".into(),
        Ret::Type(_, Type::Vec3) => "shk::Vec3".into(),
        Ret::Type(_, _) => "uint64_t".into(),
    }
}

pub fn cpp(db: &Db, source: &str) -> String {
    let als = aliases(db);
    let mut o = String::new();
    o.push_str(&format!("// natives.h: generated by shk-natives from {source}. Do not edit; regenerate.\n// SPDX-License-Identifier: MIT OR Apache-2.0\n//\n// Each function calls its native by name through the host's natives database (looked up once).\n// Call them from a script function (shk::start_script). {}\n#pragma once\n#include \"scripthook.hpp\"\n\n", db.summary()));
    o.push_str("namespace natives {\n");
    for a in &als {
        o.push_str(&format!("using {} = int32_t;\n", ident(a)));
    }
    if !als.is_empty() {
        o.push('\n');
    }
    for (ns, list) in by_namespace(db) {
        o.push_str(&format!("namespace {} {{\n", ident(&ns)));
        for n in list {
            let (sig, call) = match &n.args {
                Args::Types(v) => {
                    let names = param_names(n, v.len());
                    (v.iter().zip(&names).map(|((sp, t), p)| format!("{} {p}", cpp_arg(sp, *t, &als))).collect::<Vec<_>>().join(", "), names.join(", "))
                }
                Args::Slots(k) => {
                    let names: Vec<String> = (0..*k).map(|i| format!("a{i}")).collect();
                    (names.iter().map(|p| format!("uint64_t {p}")).collect::<Vec<_>>().join(", "), names.join(", "))
                }
                Args::Unknown => continue,
            };
            let ret = cpp_ret(&n.ret, &als);
            if !n.doc.is_empty() {
                o.push_str(&format!("/// {}\n", n.doc));
            }
            o.push_str(&format!("/// {} (identifier {})\n", n.name, id_text(n)));
            let lookup = format!("static const shk::Native shk_n_(\"{}\");", n.name);
            let sep = if call.is_empty() { "" } else { ", " };
            if ret == "void" {
                o.push_str(&format!("inline void {}({sig}) {{ {lookup} shk_n_.call_void({call}); }}\n", ident(n.short())));
            } else {
                o.push_str(&format!("inline {ret} {}({sig}) {{ {lookup} {ret} shk_r_{{}}; shk_n_.call(&shk_r_{sep}{call}); return shk_r_; }}\n", ident(n.short())));
            }
        }
        o.push_str(&format!("}}  // namespace {}\n\n", ident(&ns)));
    }
    o.push_str("}  // namespace natives\n");
    o
}

// ---- C --------------------------------------------------------------------------------------

fn c_type(t: Type) -> (&'static str, &'static str) {
    // (parameter type, ShkValue member / constructor)
    match t {
        Type::Int => ("int32_t", "INT"),
        Type::Float => ("float", "FLOAT"),
        Type::Bool => ("int", "BOOL"),
        Type::Hash => ("uint32_t", "HASH"),
        Type::Str => ("const char*", "STRING"),
        Type::Vec3 => ("ShkVec3", "VEC3"),
        Type::U64 | Type::Ptr => ("uint64_t", "U64"),
        Type::OutInt => ("int32_t*", "OUT_INT"),
        Type::OutFloat => ("float*", "OUT_FLOAT"),
        Type::OutBool => ("int32_t*", "OUT_BOOL"),
        Type::OutVec3 => ("ShkVec3*", "OUT_VEC3"),
        Type::Void => ("void", "VOID"),
    }
}

pub fn c(db: &Db, source: &str) -> String {
    let mut o = String::new();
    o.push_str(&format!(
        "/* natives_c.h: generated by shk-natives from {source}. Do not edit; regenerate.\n * SPDX-License-Identifier: MIT OR Apache-2.0\n *\n * Functions NS__NAME(...) call natives through the host's natives database. Define\n * SHK_NATIVES_HOST to an expression giving your `const ShkHost*` before including this file\n * (default: a global `shk_host` you define). Call them from a script function. {} */\n#ifndef SHK_NATIVES_C_H\n#define SHK_NATIVES_C_H\n#include <string.h>\n#include \"scripthook.h\"\n\n#ifndef SHK_NATIVES_HOST\nextern const ShkHost* shk_host;\n#define SHK_NATIVES_HOST shk_host\n#endif\n\n",
        db.summary()
    ));
    o.push_str("static inline ShkValue shk_v_INT(int32_t x) { ShkValue v; memset(&v, 0, sizeof v); v.type = SHK_TYPE_INT; v.u.i = x; return v; }\n");
    o.push_str("static inline ShkValue shk_v_FLOAT(float x) { ShkValue v; memset(&v, 0, sizeof v); v.type = SHK_TYPE_FLOAT; v.u.f = x; return v; }\n");
    o.push_str("static inline ShkValue shk_v_BOOL(int x) { ShkValue v; memset(&v, 0, sizeof v); v.type = SHK_TYPE_BOOL; v.u.i = x ? 1 : 0; return v; }\n");
    o.push_str("static inline ShkValue shk_v_HASH(uint32_t x) { ShkValue v; memset(&v, 0, sizeof v); v.type = SHK_TYPE_HASH; v.u.hash = x; return v; }\n");
    o.push_str("static inline ShkValue shk_v_STRING(const char* x) { ShkValue v; memset(&v, 0, sizeof v); v.type = SHK_TYPE_STRING; v.u.s = x; return v; }\n");
    o.push_str("static inline ShkValue shk_v_VEC3(ShkVec3 x) { ShkValue v; memset(&v, 0, sizeof v); v.type = SHK_TYPE_VEC3; v.u.v = x; return v; }\n");
    o.push_str("static inline ShkValue shk_v_U64(uint64_t x) { ShkValue v; memset(&v, 0, sizeof v); v.type = SHK_TYPE_U64; v.u.u64 = x; return v; }\n");
    for k in ["OUT_INT", "OUT_FLOAT", "OUT_BOOL", "OUT_VEC3"] {
        o.push_str(&format!("static inline ShkValue shk_v_{k}(void* x) {{ ShkValue v; memset(&v, 0, sizeof v); v.type = SHK_TYPE_{k}; v.u.p = x; return v; }}\n"));
    }
    o.push_str("static inline ShkNative shk_native_(ShkNative* slot, const char* name) { if (!*slot) *slot = SHK_NATIVES_HOST->natives->lookup(name, NULL); return *slot; }\n\n");
    for (ns, list) in by_namespace(db) {
        o.push_str(&format!("/* ---- {ns} */\n"));
        for n in list {
            let (params, vals): (Vec<String>, Vec<String>) = match &n.args {
                Args::Types(v) => {
                    let names = param_names(n, v.len());
                    v.iter().zip(&names).map(|((_, t), p)| (format!("{} {p}", c_type(*t).0), format!("shk_v_{}({p})", c_type(*t).1))).unzip()
                }
                Args::Slots(k) => (0..*k).map(|i| (format!("uint64_t a{i}"), format!("shk_v_U64(a{i})"))).unzip(),
                Args::Unknown => continue,
            };
            let (rt, rcode, rget) = match &n.ret {
                Ret::Type(_, Type::Void) => ("void", "VOID", ""),
                Ret::Type(_, Type::Float) => ("float", "FLOAT", "u.f"),
                Ret::Type(_, Type::Bool) => ("int", "BOOL", "u.i"),
                Ret::Type(_, Type::Hash) => ("uint32_t", "HASH", "u.hash"),
                Ret::Type(_, Type::Str) => ("const char*", "STRING", "u.s"),
                Ret::Type(_, Type::Vec3) => ("ShkVec3", "VEC3", "u.v"),
                Ret::Type(_, Type::U64 | Type::Ptr) => ("uint64_t", "U64", "u.u64"),
                _ => ("int32_t", "INT", "u.i"),
            };
            let fname = format!("{}__{}", ident(&ns), ident(n.short()));
            let args = if vals.is_empty() { "ShkValue shk_a_[1]; memset(shk_a_, 0, sizeof shk_a_);".to_string() } else { format!("ShkValue shk_a_[] = {{{}}};", vals.join(", ")) };
            let count = vals.len();
            o.push_str(&format!("/* {} (identifier {}) */\n", n.name, id_text(n)));
            let p = if params.is_empty() { "void".to_string() } else { params.join(", ") };
            if rt == "void" {
                o.push_str(&format!("static inline void {fname}({p}) {{ static ShkNative shk_n_; {args} SHK_NATIVES_HOST->natives->call(shk_native_(&shk_n_, \"{}\"), shk_a_, {count}, NULL); }}\n", n.name));
            } else {
                o.push_str(&format!("static inline {rt} {fname}({p}) {{ static ShkNative shk_n_; {args} ShkValue shk_r_; memset(&shk_r_, 0, sizeof shk_r_); shk_r_.type = SHK_TYPE_{rcode}; SHK_NATIVES_HOST->natives->call(shk_native_(&shk_n_, \"{}\"), shk_a_, {count}, &shk_r_); return shk_r_.{rget}; }}\n", n.name));
            }
        }
        o.push('\n');
    }
    o.push_str("#endif /* SHK_NATIVES_C_H */\n");
    o
}

// ---- Rust -----------------------------------------------------------------------------------

const RUST_KEYWORDS: [&str; 38] = [
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn",
];

fn rust_ident(s: &str) -> String {
    let i = ident(s).to_ascii_lowercase();
    if ["self", "super", "crate"].contains(&i.as_str()) {
        format!("{i}_")
    } else if RUST_KEYWORDS.contains(&i.as_str()) || ["abstract", "become", "box", "do", "final", "macro", "override", "priv", "try", "typeof", "unsized", "virtual", "yield", "gen"].contains(&i.as_str()) {
        format!("r#{i}")
    } else {
        i
    }
}

fn rs_arg(sp: &str, t: Type, als: &BTreeSet<String>) -> String {
    match t {
        Type::Int => alias_or(sp, als, "i32"),
        Type::Float => "f32".into(),
        Type::Bool => "bool".into(),
        Type::Hash => "Hash".into(),
        Type::Str => "&str".into(),
        Type::Vec3 => "Vec3".into(),
        Type::U64 | Type::Ptr => "u64".into(),
        Type::OutInt => format!("&mut {}", alias_or(sp, als, "i32")),
        Type::OutFloat => "&mut f32".into(),
        Type::OutBool => "OutBool<'_>".into(),
        Type::OutVec3 => "&mut Vec3".into(),
        Type::Void => "()".into(),
    }
}

fn rs_ret(r: &Ret, als: &BTreeSet<String>) -> String {
    match r {
        Ret::Unknown => "i32".into(),
        Ret::Type(_, Type::Void) => "()".into(),
        Ret::Type(sp, Type::Int) => alias_or(sp, als, "i32"),
        Ret::Type(_, Type::Float) => "f32".into(),
        Ret::Type(_, Type::Bool) => "bool".into(),
        Ret::Type(_, Type::Hash) => "Hash".into(),
        Ret::Type(_, Type::Str) => "String".into(),
        Ret::Type(_, Type::Vec3) => "Vec3".into(),
        Ret::Type(_, _) => "u64".into(),
    }
}

pub fn rust(db: &Db, source: &str) -> String {
    let als = aliases(db);
    let mut o = String::new();
    o.push_str(&format!("// natives.rs: generated by shk-natives from {source}. Do not edit; regenerate.\n// SPDX-License-Identifier: MIT OR Apache-2.0\n//\n// Each function calls its native by name through the host's natives database (looked up\n// once). Call them from a script function. Use it as a module (`mod natives;`).\n// {}\n\n#[allow(unused_imports)]\npub use scripthook_sdk::natives::{{Hash, NativeCell, OutBool, Result, Vec3}};\n#[allow(unused_imports)]\nuse scripthook_sdk::natives::IntoArg;\n\n", db.summary()));
    for a in &als {
        o.push_str(&format!("pub type {} = i32;\n", ident(a)));
    }
    if !als.is_empty() {
        o.push('\n');
    }
    for (ns, list) in by_namespace(db) {
        o.push_str(&format!("#[allow(non_snake_case, clippy::too_many_arguments, dead_code)]\npub mod {} {{\n    use super::*;\n\n", rust_ident(&ns)));
        let mut used = BTreeSet::new();
        for n in list {
            let (sig, args, many) = match &n.args {
                Args::Types(v) => {
                    let names: Vec<String> = param_names(n, v.len()).into_iter().map(|p| rust_ident(&p)).collect();
                    (v.iter().zip(&names).map(|((sp, t), p)| format!("{p}: {}", rs_arg(sp, *t, &als))).collect::<Vec<_>>().join(", "), names, v.len() > 16)
                }
                Args::Slots(k) => {
                    let names: Vec<String> = (0..*k).map(|i| format!("a{i}")).collect();
                    (names.iter().map(|p| format!("{p}: u64")).collect::<Vec<_>>().join(", "), names, *k > 16)
                }
                Args::Unknown => continue,
            };
            let mut f = rust_ident(n.short());
            while !used.insert(f.clone()) {
                f.push('_');
            }
            let ret = rs_ret(&n.ret, &als);
            if !n.doc.is_empty() {
                o.push_str(&format!("    /// {}\n    ///\n", n.doc));
            }
            o.push_str(&format!("    /// `{}` (identifier {})\n", n.name, id_text(n)));
            let call = if many {
                format!("let mut k_ = Vec::new(); let v_ = vec![{}]; N.call(v_)", args.iter().map(|a| format!("IntoArg::into_arg({a}, &mut k_)")).collect::<Vec<_>>().join(", "))
            } else if args.is_empty() {
                "N.call(())".to_string()
            } else {
                format!("N.call(({},))", args.join(", "))
            };
            o.push_str(&format!("    pub fn {f}({sig}) -> Result<{ret}> {{\n        static N: NativeCell = NativeCell::new(\"{}\");\n        {call}\n    }}\n", n.name));
        }
        o.push_str("}\n\n");
    }
    o
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_all_three() {
        let d = crate::db::parse("identifier\targs\treturns\tname\tparams\n0x1\t0\tPed\tPLAYER::PLAYER_PED_ID\t-\n-\tPlayer, BOOL\tvoid\tPLAYER::SET_PLAYER_INVINCIBLE\tplayer, toggle\n-\tEntity, BOOL\tVector3\tENTITY::GET_ENTITY_COORDS\t-\n-\tHash, int*, int\tBOOL\tSTATS::STAT_GET_INT\t-\n-\t2\t0\tTEST::TYPE\t-\n-\tconst char*\tint\tSTR_LEN\t-\n");
        let h = cpp(&d, "t.tsv");
        assert!(h.contains("using Ped = int32_t;"), "{h}");
        assert!(h.contains("namespace PLAYER {"));
        assert!(h.contains("inline void SET_PLAYER_INVINCIBLE(Player player, bool toggle)"), "{h}");
        assert!(h.contains("inline shk::Vec3 GET_ENTITY_COORDS(Entity p0, bool p1)"), "{h}");
        assert!(h.contains("inline bool STAT_GET_INT(shk::Hash p0, int32_t* p1, int32_t p2)"), "{h}");
        assert!(h.contains("namespace NATIVES {"));
        let r = rust(&d, "t.tsv");
        assert!(r.contains("pub mod player {"));
        assert!(r.contains("pub fn set_player_invincible(player: Player, toggle: bool) -> Result<()>"), "{r}");
        assert!(r.contains("pub fn r#type(a0: u64, a1: u64) -> Result<()>"), "{r}");
        assert!(r.contains("pub fn str_len(p0: &str) -> Result<i32>"), "{r}");
        let c = c(&d, "t.tsv");
        assert!(c.contains("static inline int32_t PLAYER__PLAYER_PED_ID(void)"), "{c}");
        assert!(c.contains("static inline ShkVec3 ENTITY__GET_ENTITY_COORDS(int32_t p0, int p1)"), "{c}");
    }
}
